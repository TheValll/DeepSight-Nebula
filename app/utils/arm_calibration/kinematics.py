"""Robot model for the arm self-calibration: URDF kinematics and servo calibration.

Everything is read from the hardware robot description generated by xacro
(hiwonder_xarm_esp32_moveit_config/config/hiwonder_esp32.urdf.xacro), so the
model always matches the installed configuration.
"""
import subprocess
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation

NOMINAL_RADIANS_PER_RAW = 4.1887902047863905 / 1000.0
ARM = ['limb1_to_base_link_joint', 'limb2_to_limb1_joint', 'limb3_to_limb2_joint',
       'limb4_to_limb3_joint', 'limb5_to_limb4_joint']
CAMERA_MOUNT_LINK = 'camera_support_link'      # child of the limb4 -> camera mount joint
CAMERA_FRAME = 'camera_left_optical_frame'
TCP_FRAME = 'gripper_tcp_link'


def homogeneous(rotation, translation):
    matrix = np.eye(4)
    matrix[:3, :3] = rotation
    matrix[:3, 3] = translation
    return matrix


def rpy_matrix(roll, pitch, yaw):
    return Rotation.from_euler('xyz', [roll, pitch, yaw]).as_matrix()


def axis_rotation(axis, angle):
    axis = np.asarray(axis, float)
    return Rotation.from_rotvec(axis / np.linalg.norm(axis) * angle).as_matrix()


def robot_description_xml():
    command = (
        'xacro "$(ros2 pkg prefix hiwonder_xarm_esp32_moveit_config)'
        '/share/hiwonder_xarm_esp32_moveit_config/config/hiwonder_esp32.urdf.xacro" '
        'use_mock_hardware:=false read_only:=true '
        'initial_positions_file:="$(ros2 pkg prefix hiwonder_xarm_esp32_moveit_config)'
        '/share/hiwonder_xarm_esp32_moveit_config/config/initial_positions.yaml"')
    result = subprocess.run(['bash', '-c', command], capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError('xacro failed (source ROS and app/install first):\n' + result.stderr)
    return result.stdout


class JointCalibration:
    """raw <-> radians conversion of one servo, as in HiwonderSystem."""

    def __init__(self, raw_reference, ros_reference, units_per_raw, direction,
                 raw_min, raw_max):
        self.raw_reference = raw_reference
        self.ros_reference = ros_reference
        self.units_per_raw = units_per_raw
        self.direction = direction
        self.raw_min = raw_min
        self.raw_max = raw_max

    def to_radians(self, raw):
        return self.ros_reference + self.direction * (raw - self.raw_reference) * self.units_per_raw

    def to_raw(self, radians):
        return self.raw_reference + (radians - self.ros_reference) / (self.direction * self.units_per_raw)

    def as_dict(self):
        return dict(vars(self))


class Robot:
    def __init__(self, xml_text=None):
        root = ET.fromstring(xml_text or robot_description_xml())
        self.joints = {}
        self.limits = {}
        for joint in root.findall('joint'):
            origin = joint.find('origin')
            xyz = [float(v) for v in origin.get('xyz', '0 0 0').split()] if origin is not None else [0, 0, 0]
            rpy = [float(v) for v in origin.get('rpy', '0 0 0').split()] if origin is not None else [0, 0, 0]
            axis = joint.find('axis')
            self.joints[joint.find('child').get('link')] = {
                'name': joint.get('name'), 'type': joint.get('type'),
                'parent': joint.find('parent').get('link'),
                'origin': homogeneous(rpy_matrix(*rpy), xyz),
                'axis': [float(v) for v in axis.get('xyz').split()] if axis is not None else None,
            }
            limit = joint.find('limit')
            if limit is not None and limit.get('lower') is not None:
                self.limits[joint.get('name')] = (float(limit.get('lower')), float(limit.get('upper')))
        self.calibration = {}
        for joint in root.findall('ros2_control/joint'):
            params = {p.get('name'): p.text for p in joint.findall('param')}
            if 'servo_id' in params:
                self.calibration[joint.get('name')] = JointCalibration(
                    float(params['raw_reference']), float(params['ros_reference']),
                    float(params['units_per_raw']), float(params['direction']),
                    int(params['raw_min']), int(params['raw_max']))

    @property
    def camera_mount(self):
        return self.joints[CAMERA_MOUNT_LINK]['origin']

    def joint_axis(self, child_link):
        return np.asarray(self.joints[child_link]['axis'], float)

    def transform(self, link, positions, stop='base_link', overrides=None):
        """stop <- link for the joint positions (dict name -> rad or m)."""
        overrides = overrides or {}
        matrix = np.eye(4)
        while link != stop:
            joint = self.joints[link]
            step = overrides.get(link, joint['origin'])
            if joint['type'] in ('revolute', 'continuous'):
                step = step @ homogeneous(
                    axis_rotation(joint['axis'], positions.get(joint['name'], 0.0)), np.zeros(3))
            elif joint['type'] == 'prismatic':
                step = step @ homogeneous(
                    np.eye(3), np.asarray(joint['axis']) * positions.get(joint['name'], 0.0))
            matrix = step @ matrix
            link = joint['parent']
        return matrix
